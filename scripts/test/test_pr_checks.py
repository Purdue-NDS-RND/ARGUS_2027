def run(repo, env):
    out = io.StringIO()
    code = pr_checks.run_gates(Path(repo), env, out=out)
    return code, out.getvalue()


def pr_env(repo, title="Add a thing", body="What changed: a thing."):
    return {
        "GITHUB_EVENT_NAME": "pull_request",
        "PR_BASE_SHA": git(repo, "rev-parse", "origin/main"),
        "PR_HEAD_SHA": git(repo, "rev-parse", "HEAD"),
        "PR_TITLE": title,
        "PR_BODY": body,
    }


