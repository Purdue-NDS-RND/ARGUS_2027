# --- Size gate ------------------------------------------------------------------


def test_large_added_file_fails_and_can_be_waived(repo):
    write(repo, "docs/big.bin", b"\0" * (6 * MB))
    write(repo, "docs/small.bin", b"\0" * MB)
    commit(repo, "Add files")
    code, out = run(repo, pr_env(repo))
    assert code == 1
    assert "docs/big.bin" in out and "docs/small.bin" not in out
    code, out = run(repo, pr_env(repo, body="[large-file: calibration board scan]"))
    assert code == 0
    assert "WAIVED size" in out
