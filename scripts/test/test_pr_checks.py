# --- Markers --------------------------------------------------------------------


def test_marker_needs_a_reason():
    assert pr_checks.find_marker("[tests: n/a docs only]", "tests") == "docs only"
    assert pr_checks.find_marker("[tests: n/a]", "tests") is None
    assert pr_checks.find_marker("[tests: n/a <reason>]", "tests") is None
    assert pr_checks.find_marker("[tuning: issue #9 asks for it]", "tuning") == "issue #9 asks for it"
    assert pr_checks.find_marker("[large-file: calibration board]", "large-file") == "calibration board"
    assert pr_checks.find_marker("[hygiene: waived quoting an upstream log]", "hygiene")
    assert pr_checks.find_marker(None, "tests") is None


def test_marker_inside_html_comment_does_not_count():
    body = "<!-- e.g. [tuning: issue asks for it] -->\nNo waivers."
    assert pr_checks.find_marker(body, "tuning") is None


