def test_commit_msg_hook(repo, tmp_path_factory, capsys):
    msg = tmp_path_factory.mktemp("msg") / "COMMIT_EDITMSG"
    msg.write_text("Add detector\n\n# Co-Authored-By: Claude\n")
    assert pr_checks.main(["commit-msg", str(msg)], cwd=repo) == 0
    msg.write_text("Add detector\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
    assert pr_checks.main(["commit-msg", str(msg)], cwd=repo) == pr_checks.EXIT_VIOLATION
    assert "AI attribution" in capsys.readouterr().out


def test_hook_fails_open_on_error(repo, capsys):
    assert pr_checks.main(["commit-msg", str(Path(repo) / "missing-file")], cwd=repo) == 0
    assert "not blocking" in capsys.readouterr().out


