# --- Hygiene gate ---------------------------------------------------------------


def test_hygiene_checks_commit_messages_title_body_and_files(repo):
    write(repo, "README.md", "more\n")
    commit(repo, "Docs\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    code, out = run(repo, pr_env(repo))
    assert code == 1
    assert "commit" in out and "message" in out

    git(repo, "commit", "-q", "--amend", "--no-verify", "-m", "Docs")
    assert run(repo, pr_env(repo))[0] == 0
    assert run(repo, pr_env(repo, title="Docs via Claude"))[0] == 1
    assert run(repo, pr_env(repo, body="Ran on nsds15."))[0] == 1

    write(repo, "README.md", f"cd {HOME}\n")
    commit(repo, "Docs again")
    code, out = run(repo, pr_env(repo))
    assert code == 1
    assert "README.md:1" in out


def test_hygiene_waiver(repo):
    write(repo, "README.md", f"cd {HOME}\n")
    commit(repo, "Docs")
    code, out = run(repo, pr_env(repo, body="[hygiene: waived quoting a user's bug report]"))
    assert code == 0
    assert "WAIVED hygiene" in out


