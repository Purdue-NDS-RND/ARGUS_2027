#!/usr/bin/env python3
"""Sim copies of the live sequence files, so the tuning a live file flies with can be flown in Gazebo. No ROS needed.

  python3 tools/sim_sequence_copies.py            # check the committed copies are up to date (also --check)
  python3 tools/sim_sequence_copies.py --write    # regenerate them after a live file changed

A sim copy is its live file, line for line, with four changes and no others:

  target_latitude, target_longitude   the sim's default target (a scenario sets its own)
  fake_drop                           true: a sim copy never commands a release
  camera_mode, airframe               the sim's camera and vehicle, for projection v2
  the note above the coordinates      says it is a sim copy

Every gain, height, deadband, dwell and flag is the live file's. The copies are
committed beside the live files as sim_<name>; a test (tools/test/
test_sim_sequence_copies.py) fails when one is out of date, so a tuned value
changed in a live file cannot leave its sim copy behind. The live files are
only read.
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SEQUENCES = REPO / "src" / "drone_mission_demo" / "config" / "sequences"

# Live file -> its sim copy. A new live sequence (the 2027 ones) is added here.
COPIES = {
    "package_drop_live.yaml": "sim_package_drop_live.yaml",
    "package_delivery_live.yaml": "sim_package_delivery_live.yaml",
}

# Where the 2026 demo sequences put the target: beside SITL's default home.
SIM_LATITUDE = -35.3631271
SIM_LONGITUDE = 149.1653479
SIM_CAMERA_MODE = "sim_delivery"
SIM_AIRFRAME = "sim_iris_downcam"

CHANGED_KEYS = {"target_latitude", "target_longitude", "fake_drop", "camera_mode", "airframe"}

_SETTING = re.compile(r"^(?P<indent>\s*)(?P<key>[A-Za-z_]\w*):(?P<gap>\s*)(?P<value>[^#\s][^#]*?)?(?P<tail>\s*#.*)?$")
_CAMERA_COMMENTS = {
    "camera_mode": "Sensor mode the detector's images come from (argus_camera modes.yaml). Read only with use_frame_time_pose on.",
    "airframe": "Airframe whose camera mount is used (argus_camera robot.yaml). Read only with use_frame_time_pose on.",
}


class CopyError(Exception):
    """A live file a sim copy cannot be made from. The message says why."""


def _with_value(match: "re.Match", value: str) -> str:
    """The setting's line with a new value, its comment kept in the column it was in where that fits."""
    head = f"{match['indent']}{match['key']}:{match['gap']}{value}"
    tail = match["tail"]
    if not tail:
        return head
    comment = tail.lstrip()
    column = len(match.group(0)) - len(comment)
    return head + " " * max(1, column - len(head)) + comment


def _header(live_name: str) -> list:
    return [
        f"# GENERATED by tools/sim_sequence_copies.py from {live_name}: do not edit.",
        "# The live file with sim coordinates, the sim camera named and fake_drop on, and",
        "# nothing else changed, so its tuning can be flown in Gazebo (the live_tuning",
        "# scenarios under sim/scenarios/). After changing the live file, run",
        "# python3 tools/sim_sequence_copies.py --write",
    ]


def sim_copy_text(live_text: str, live_name: str) -> str:
    """The sim copy of a live sequence file's text."""
    lines = live_text.splitlines()
    out: list = []
    targets = drops = 0
    for line in lines:
        match = _SETTING.match(line)
        key = match["key"] if match and match["value"] is not None else None
        if key in ("camera_mode", "airframe"):
            continue  # replaced by the sim's, beside the coordinates
        if key == "target_latitude":
            targets += 1
            while out and out[-1].lstrip().startswith("#"):
                out.pop()  # the live file's note about its coordinates
            out.append(f"{match['indent']}# Sim copy: the sim's default target; a scenario sets its own object's position.")
            out.append(_with_value(match, f"{SIM_LATITUDE:.7f}"))
        elif key == "target_longitude":
            out.append(_with_value(match, f"{SIM_LONGITUDE:.7f}"))
            for name, value in (("camera_mode", SIM_CAMERA_MODE), ("airframe", SIM_AIRFRAME)):
                out.append(f"{match['indent']}{name}: {value} # {_CAMERA_COMMENTS[name]}")
        elif key == "fake_drop":
            drops += 1
            out.append(_with_value(match, "true"))
        else:
            out.append(line)
    if not targets:
        raise CopyError(f"{live_name}: no mission has a target_latitude, so there is no target to move into the sim")
    if not drops:
        raise CopyError(f"{live_name}: no mission has a fake_drop setting, so the copy could not be kept from releasing")
    text = "\n".join(_header(live_name) + out) + "\n"
    _verify(live_text, text, live_name)
    return text


def _verify(live_text: str, sim_text: str, live_name: str) -> None:
    """Read both files back: the copy must differ from the live file in the five settings and nowhere else."""
    import yaml

    live, sim = yaml.safe_load(live_text), yaml.safe_load(sim_text)
    try:
        live_root, sim_root = live["mission_sequence"], sim["mission_sequence"]
        live_missions, sim_missions = live_root["missions"], sim_root["missions"]
    except (KeyError, TypeError) as exc:
        raise CopyError(f"{live_name}: not a mission sequence file ({exc!r})") from exc
    rest = lambda root: {k: v for k, v in root.items() if k != "missions"}  # noqa: E731
    if rest(live_root) != rest(sim_root) or len(live_missions) != len(sim_missions):
        raise CopyError(f"{live_name}: the copy's sequence settings or mission list came out different from the live file's")
    for before, after in zip(live_missions, sim_missions):
        strip = lambda entry: {k: v for k, v in entry.items() if k != "config"}  # noqa: E731
        old, new = before.get("config") or {}, after.get("config") or {}
        different = {key for key in set(old) | set(new) if old.get(key) != new.get(key)}
        tracking = "target_latitude" in old
        if tracking and "fake_drop" not in old:
            # A mission without the setting would default to a real release.
            raise CopyError(f"{live_name}: mission '{before.get('name')}' has a target but no fake_drop setting, so its copy could not be kept from releasing")
        expected = dict(old)
        if tracking:
            expected.update(target_latitude=SIM_LATITUDE, target_longitude=SIM_LONGITUDE, camera_mode=SIM_CAMERA_MODE, airframe=SIM_AIRFRAME)
        if "fake_drop" in old:
            expected["fake_drop"] = True
        if strip(before) != strip(after) or not different <= CHANGED_KEYS or new != expected:
            raise CopyError(
                f"{live_name}: mission '{before.get('name')}' did not copy cleanly (settings that differ: {sorted(different)}); "
                "the generator reads one `key: value` per line"
            )


def stale(directory: Path) -> list:
    """(copy name, reason) for every sim copy in the directory that is missing or out of date."""
    problems = []
    for live_name, sim_name in sorted(COPIES.items()):
        live_path, sim_path = directory / live_name, directory / sim_name
        if not live_path.is_file():
            problems.append((sim_name, f"its live file {live_name} is missing"))
            continue
        expected = sim_copy_text(live_path.read_text(encoding="utf-8"), live_name)
        if not sim_path.is_file():
            problems.append((sim_name, "missing"))
        elif sim_path.read_text(encoding="utf-8") != expected:
            problems.append((sim_name, f"out of date with {live_name}"))
    return problems


def write(directory: Path) -> list:
    written = []
    for live_name, sim_name in sorted(COPIES.items()):
        text = sim_copy_text((directory / live_name).read_text(encoding="utf-8"), live_name)
        path = directory / sim_name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            written.append(sim_name)
    return written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if a committed copy is missing or out of date (the default)")
    mode.add_argument("--write", action="store_true", help="regenerate the copies")
    parser.add_argument("--dir", type=Path, default=SEQUENCES, help="the sequences folder (default: the repo's)")
    args = parser.parse_args(argv)
    try:
        if args.write:
            written = write(args.dir)
            print("\n".join(f"wrote {name}" for name in written) if written else "every sim copy was already up to date")
            return 0
        problems = stale(args.dir)
    except (CopyError, OSError) as exc:
        print(f"sim_sequence_copies: {exc}", file=sys.stderr)
        return 2
    for name, reason in problems:
        print(f"{name}: {reason}; run python3 tools/sim_sequence_copies.py --write")
    if not problems:
        print(f"{len(COPIES)} sim copies up to date")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
