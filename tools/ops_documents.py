#!/usr/bin/env python3
"""The required documents (OPS-09): the SOP, the emergency procedures and the checklists, written from the code.

  python3 tools/ops_documents.py            # write docs/ops/sop.md, emergency_procedures.md and checklists.md
  python3 tools/ops_documents.py --check    # exit 1 if a committed document is not what would be written now

The parts that could drift from the aircraft are not typed here; they are
read at the moment the documents are written:

  - the preflight's checks, what each means with its limit, and what to do
    about a NO-GO: `drone_utils/preflight.py` (CHECKS, GUIDE, Limits);
  - what the flight controller does by itself when a failsafe trips: the
    values of `platform/fcu/argus_2027.param`, decoded;
  - the fence's margin a commanded point keeps (`safety_limits.py`), the
    release states the actuation lock allows (`actuation_lock.py`).

The rest (who does what, in what order, what a person does in an emergency)
is the text below. `--check` runs with the tests (scripts/check.sh), so a
limit changed in the preflight, or a failsafe changed in the baseline,
fails the check until the documents are written again and read.

No ROS imports.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
for path in (ROOT / "src" / "drone_utils", ROOT / "src" / "drone_mission_core"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from drone_mission_core import actuation_lock, safety_limits  # noqa: E402
from drone_utils import preflight  # noqa: E402

OUT = ROOT / "docs" / "ops"
BASELINE = ROOT / "platform" / "fcu" / "argus_2027.param"
HEADER = "<!-- GENERATED by tools/ops_documents.py: do not edit. Change the tool or what it reads, then run it. -->"

# ArduCopter 4.6 parameter values, as its parameter documentation names them. Only actions; a value not listed is
# written as its number, and a test fails so that it is named here before the document goes out.
BATTERY_ACTIONS = {0: "nothing", 1: "lands where it is", 2: "returns to the takeoff point (RTL)", 3: "returns by its own track, or RTL", 4: "returns by its own track, or lands", 5: "stops its motors"}
RADIO_ACTIONS = {0: "nothing", 1: "returns to the takeoff point (RTL)", 3: "lands where it is", 4: "returns by its own track, or RTL", 5: "returns by its own track, or lands"}
GROUND_STATION_ACTIONS = {0: "nothing", 1: "returns to the takeoff point (RTL)", 3: "returns by its own track, or RTL", 4: "returns by its own track, or lands", 5: "lands where it is"}
EKF_ACTIONS = {1: "lands where it is", 2: "holds its height, drifting (AltHold)", 3: "lands where it is, in every mode"}
FENCE_ACTIONS = {1: "returns to the takeoff point (RTL), or lands", 2: "lands where it is", 3: "returns by its own track, RTL, or lands", 4: "brakes, or lands", 5: "returns by its own track, or lands"}


class DocumentError(ValueError):
    """The documents cannot be written from what is in the repo. The message says why."""


def baseline(path: Path = BASELINE) -> Dict[str, float]:
    return preflight.read_param_file(path)


def _action(table: Dict[int, str], params: Dict[str, float], name: str) -> str:
    if name not in params:
        raise DocumentError(f"the baseline has no {name}: the emergency procedures cannot say what the aircraft does")
    value = int(params[name])
    if value not in table:
        raise DocumentError(f"{name} is {value}, which this tool has no words for: add it to the tool before the document is written")
    return table[value]


def fence_trigger(params: Dict[str, float]) -> str:
    """What breaches the fence, from FENCE_ENABLE and FENCE_TYPE's bits (0 ceiling, 1 circle, 2 polygon, 3 floor)."""
    if int(params.get("FENCE_ENABLE", 0)) != 1:
        raise DocumentError("the baseline's FENCE_ENABLE is not 1: the procedures are written for an aircraft with its fence on")
    kinds = int(params["FENCE_TYPE"])
    parts = []
    if kinds & 4:
        parts.append("outside the polygon")
    if kinds & 2:
        parts.append(f"over {params['FENCE_RADIUS']:g} m from home")
    if kinds & 1:
        parts.append(f"above {params['FENCE_ALT_MAX']:g} m")
    if kinds & 8:
        parts.append(f"below {params['FENCE_ALT_MIN']:g} m")
    if not parts or kinds >= 16:
        raise DocumentError(f"FENCE_TYPE is {kinds}, which this tool has no words for")
    return " or ".join(parts)


def failsafe_exceptions(params: Dict[str, float]) -> Dict[str, str]:
    """When a failsafe does NOT act, from FS_OPTIONS' bits 0 to 4: {the row it qualifies: the exception}."""
    options = int(params.get("FS_OPTIONS", 0))
    if options >= 64:
        raise DocumentError(f"FS_OPTIONS is {options}, which has a bit this tool has no words for")
    radio, station = [], []
    if options & 1:
        radio.append("in AUTO")
    if options & 4:
        radio.append("in GUIDED (the mission stack's mode)")
    if options & 2:
        station.append("in AUTO")
    if options & 16:
        station.append("while a person is flying it in LOITER, ALT_HOLD, STABILIZE or another pilot mode")
    notes = {}
    if radio:
        notes["Transmitter lost"] = "not " + " or ".join(radio)
    if station:
        notes["Ground station lost"] = "not " + " or ".join(station)
    if options & 8:
        notes["Battery low"] = notes["Battery critical"] = "a landing already under way goes on"
        for name in ("Transmitter lost", "Ground station lost"):
            notes[name] = "; ".join(filter(None, [notes.get(name), "a landing already under way goes on"]))
    return notes


def failsafes(params: Dict[str, float]) -> List[Dict[str, str]]:
    """What the flight controller does by itself, from the baseline's values: one row for each trigger."""
    cells = preflight.Limits().cells
    # ArduPilot's BATT_LOW_TIMER is how long the voltage must stay under either level, low or critical.
    timer = f" for {params['BATT_LOW_TIMER']:g} s"
    rows = [
        {"what": "Fence breached", "when": fence_trigger(params), "does": _action(FENCE_ACTIONS, params, "FENCE_ACTION"), "params": "FENCE_TYPE, FENCE_ACTION"},
        {"what": "Battery low", "when": f"under {params['BATT_LOW_VOLT']:g} V ({params['BATT_LOW_VOLT'] / cells:.2f} V a cell){timer}",
         "does": _action(BATTERY_ACTIONS, params, "BATT_FS_LOW_ACT"), "params": "BATT_LOW_VOLT, BATT_FS_LOW_ACT"},  # fmt: skip
        {"what": "Battery critical", "when": f"under {params['BATT_CRT_VOLT']:g} V ({params['BATT_CRT_VOLT'] / cells:.2f} V a cell){timer}", "does": _action(BATTERY_ACTIONS, params, "BATT_FS_CRT_ACT"),
         "params": "BATT_CRT_VOLT, BATT_FS_CRT_ACT"},  # fmt: skip
        {"what": "Transmitter lost", "when": f"the throttle channel under {params['FS_THR_VALUE']:g}, or no signal", "does": _action(RADIO_ACTIONS, params, "FS_THR_ENABLE"), "params": "FS_THR_ENABLE"},
        {"what": "Ground station lost", "when": f"no heartbeat from it for {params['FS_GCS_TIMEOUT']:g} s", "does": _action(GROUND_STATION_ACTIONS, params, "FS_GCS_ENABLE"), "params": "FS_GCS_ENABLE"},
        {"what": "Position estimate lost (EKF)", "when": f"variance over {params['FS_EKF_THRESH']:g}", "does": _action(EKF_ACTIONS, params, "FS_EKF_ACTION"), "params": "FS_EKF_ACTION"},
    ]
    exceptions = failsafe_exceptions(params)
    for row in rows:
        row["unless"] = exceptions.get(row["what"], "")
        if row["unless"]:
            row["params"] += ", FS_OPTIONS"
    return rows


def _does(row: Dict[str, str]) -> str:
    return row["does"] + (f"; {row['unless']}" if row["unless"] else "")


def gripper_note(params: Dict[str, float]) -> str:
    """Whether a failsafe lets the payload go: FS_OPTIONS bit 5."""
    if int(params.get("FS_OPTIONS", 0)) & 32:
        raise DocumentError("FS_OPTIONS has bit 5 set: a failsafe would release the gripper. The baseline must keep it clear")
    return "No failsafe lets the payload or the bucket go (`FS_OPTIONS` bit 5 is clear): what is carried comes down with the aircraft."


