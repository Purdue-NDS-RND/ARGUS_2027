             "| Lead | Decides what is flown, any override, any break of the freeze, when to roll back | Flies or types during a flight |",
             "| Safety pilot | Holds the transmitter from arming to disarming; takes over at any doubt | Looks at a screen in flight |",
             "| Operator | Types the commands, reads the preflight and the modes aloud | Sends a mode or a command during an autonomous flight: it costs the autonomy bonus |",
             "| Spotter | Watches the aircraft and the flight area, calls positions and people | Looks away |", "",
             "## Before the competition", "",
             "1. The flight controller holds the 2027 baseline and the site's fence (`platform/fcu/README.md`).",
