def documents() -> Dict[str, str]:
    params = baseline()
    return {"sop.md": sop(params), "emergency_procedures.md": emergency_procedures(params), "checklists.md": checklists()}


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Write the SOP, the emergency procedures and the checklists from the code.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if a committed document differs from what would be written")
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args(argv)
    try:
        made = documents()
    except (DocumentError, OSError, KeyError) as problem:
        print(f"ops_documents: {problem}", file=sys.stderr)
        return 2
    out = Path(args.out)
    stale = [name for name, text in made.items() if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text]
    if args.check:
        for name in stale:
            print(f"{out / name}: not what tools/ops_documents.py writes now: run it, read the difference, commit")
        print("documents: " + ("DRIFTED" if stale else "as generated"))
        return 1 if stale else 0
    out.mkdir(parents=True, exist_ok=True)
    for name, text in made.items():
        (out / name).write_text(text, encoding="utf-8")
        print(f"wrote {out / name}" + ("" if name in stale else " (unchanged)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
